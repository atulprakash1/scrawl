// Scrawl's only build step, and an optional one: node tools/bundle.mjs (Node 18+, no dependencies).
//
// 1. app/js/templates.js: what "Hook up Claude" writes into another repo. A page opened from file://
//    can't read files next to it, so the CLAUDE.md protocol, .claude/commands/ and .scrawl/hooks/
//    are copied in here. Run this again after changing any of them, and commit the result.
// 2. dist/scrawl.html: the whole board in one file (styles, fonts, libraries, scripts), to copy
//    into any repo. Not committed.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(ROOT, p), 'utf8').replace(/\r\n/g, '\n');
const SECTION = '## Scrawl work tracking';

/* ---------- templates.js ---------- */

// The protocol is the "Scrawl work tracking" section of our own CLAUDE.md, up to the next "## ".
function protocol() {
  const md = read('CLAUDE.md');
  const start = md.indexOf(`\n${SECTION}\n`);
  if (start < 0) throw new Error(`CLAUDE.md has no "${SECTION}" section`);
  const rest = md.slice(start + 1);
  const end = rest.indexOf('\n## ', SECTION.length);
  return (end < 0 ? rest : rest.slice(0, end + 1)).replace(/\n+$/, '\n');
}

function folder(dir) {
  if (!existsSync(join(ROOT, dir))) throw new Error(`${dir} is missing (is the board checked out at .scrawl/?)`);
  return Object.fromEntries(readdirSync(join(ROOT, dir)).sort()
    .filter((name) => !name.startsWith('.'))
    .map((name) => [`${dir}/${name}`, read(`${dir}/${name}`)]));
}

const templates = {
  section: SECTION,
  protocol: protocol(),
  files: { ...folder('.claude/commands'), ...folder('.scrawl/hooks') },
};

writeFileSync(join(ROOT, 'app/js/templates.js'),
  '/* Generated by tools/bundle.mjs from CLAUDE.md, .claude/commands/ and .scrawl/hooks/. Don\'t edit by hand. */\n' +
  `window.Scrawl.templates = ${JSON.stringify(templates, null, 2)};\n`);
console.log(`app/js/templates.js: protocol + ${Object.keys(templates.files).length} files`);

/* ---------- dist/scrawl.html ---------- */

// Inside an inline <script>, "</script" would end it early; "<\/script" means the same to JS.
const inlineJs = (js) => js.replace(/<\/script/gi, '<\\/script');

function inlineCss(path) {
  return read(path).replace(/url\('([^']+\.woff2)'\)/g, (_, rel) => {
    const font = readFileSync(join(ROOT, dirname(path), rel)).toString('base64');
    return `url('data:font/woff2;base64,${font}')`;
  });
}

let html = read('scrawl.html')
  .replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, href) => `<style>\n${inlineCss(href)}</style>`)
  .replace(/<script src="([^"]+)"><\/script>/g, (_, src) => `<script>\n${inlineJs(read(src))}\n</script>`);
if (/(?:src|href)="(?:app|vendor)\//.test(html)) throw new Error('dist/scrawl.html still points at a local file');

mkdirSync(join(ROOT, 'dist'), { recursive: true });
writeFileSync(join(ROOT, 'dist/scrawl.html'), html);
console.log(`dist/scrawl.html: ${(Buffer.byteLength(html) / 1024).toFixed(0)} KB, one file`);
